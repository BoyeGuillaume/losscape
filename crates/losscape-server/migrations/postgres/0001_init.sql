CREATE TABLE projects (
    id          BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name        TEXT NOT NULL UNIQUE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE runs (
    id                 UUID PRIMARY KEY,  -- UUIDv7, generated by the client
    project_id         BIGINT NOT NULL REFERENCES projects (id),
    name               TEXT NOT NULL,
    group_name         TEXT,
    tags               TEXT[] NOT NULL DEFAULT '{}',
    notes              TEXT NOT NULL DEFAULT '',
    config             JSONB NOT NULL DEFAULT '{}',
    summary            JSONB NOT NULL DEFAULT '{}',
    environment        JSONB NOT NULL DEFAULT '{}',
    state              TEXT NOT NULL DEFAULT 'running'
                       CHECK (state IN ('running', 'finished', 'failed', 'killed', 'crashed')),
    exit_code          INT,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    client_created_at  TIMESTAMPTZ,
    heartbeat_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at        TIMESTAMPTZ,
    -- Ingest dedup window: every seq < next_seq is stored, plus those in pending_seqs
    -- (stored out of order). Kept on the run row instead of one row per batch, which
    -- would grow by ~36k rows per run-hour.
    next_seq           BIGINT NOT NULL DEFAULT 0,
    pending_seqs       BIGINT[] NOT NULL DEFAULT '{}',
    last_seq           BIGINT  -- reported by RunFinish
);

CREATE INDEX runs_project_created ON runs (project_id, created_at DESC);
CREATE INDEX runs_tags ON runs USING GIN (tags);
CREATE INDEX runs_config ON runs USING GIN (config jsonb_path_ops);
CREATE INDEX runs_running_heartbeat ON runs (heartbeat_at) WHERE state = 'running';

-- A name unique within a project that points to exactly one run; setting it again moves it.
CREATE TABLE run_aliases (
    project_id  BIGINT NOT NULL REFERENCES projects (id),
    alias       TEXT NOT NULL,
    run_id      UUID NOT NULL REFERENCES runs (id) ON DELETE CASCADE,
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (project_id, alias)
);
CREATE INDEX run_aliases_run ON run_aliases (run_id);
